-- 1. BẢNG DANH MỤC SỰ KIỆN (Categories)
CREATE TABLE Categories (
    category_id INT IDENTITY(1,1) PRIMARY KEY,
    category_name NVARCHAR(100) NOT NULL,
    color_hex VARCHAR(20) NOT NULL DEFAULT '#ffd400'
);
GO

-- 2. BẢNG NGƯỜI DÙNG (Users)
CREATE TABLE Users (
    user_id INT IDENTITY(1,1) PRIMARY KEY,
    full_name NVARCHAR(150) NOT NULL,
    email VARCHAR(150) NOT NULL UNIQUE,
    phone VARCHAR(20),
    password VARCHAR(255) NOT NULL,
    role VARCHAR(20) NOT NULL DEFAULT 'CUSTOMER', -- 'ADMIN', 'CUSTOMER'
    created_at DATETIME DEFAULT GETDATE()
);
GO

-- 3. BẢNG SỰ KIỆN (Events)
CREATE TABLE Events (
    event_id INT IDENTITY(1,1) PRIMARY KEY,
    category_id INT NOT NULL,
    title NVARCHAR(255) NOT NULL,
    description NVARCHAR(MAX),
    location NVARCHAR(255) NOT NULL,
    event_date DATETIME NOT NULL,
    min_price DECIMAL(18,2) NOT NULL DEFAULT 0,
    banner_color VARCHAR(20) DEFAULT '#3a68ff',
    tag_label NVARCHAR(100),
    is_featured BIT DEFAULT 0,
    total_capacity INT NOT NULL DEFAULT 2500,
    status NVARCHAR(50) DEFAULT N'Sắp diễn ra',
    image_url VARCHAR(255) NULL, -- đường dẫn ảnh sự kiện (tương đối so với context path)
    created_at DATETIME DEFAULT GETDATE(),
    FOREIGN KEY (category_id) REFERENCES Categories(category_id)
);
GO

-- 4. BẢNG LOẠI VÉ (TicketTypes)
CREATE TABLE TicketTypes (
    ticket_type_id INT IDENTITY(1,1) PRIMARY KEY,
    event_id INT NOT NULL,
    type_name NVARCHAR(100) NOT NULL, -- 'VIP', 'Thường', 'Sinh viên'
    description NVARCHAR(255),
    price DECIMAL(18,2) NOT NULL,
    total_quantity INT NOT NULL,
    sold_quantity INT NOT NULL DEFAULT 0,
    bar_color VARCHAR(30) DEFAULT '#3a68ff',
    FOREIGN KEY (event_id) REFERENCES Events(event_id)
);
GO

-- 5. BẢNG ĐƠN HÀNG (Orders)
CREATE TABLE Orders (
    order_id INT IDENTITY(1,1) PRIMARY KEY,
    order_code VARCHAR(30) NOT NULL UNIQUE, -- '#TK-0936'
    user_id INT NULL,
    event_id INT NOT NULL,
    customer_name NVARCHAR(150) NOT NULL,
    customer_email VARCHAR(150) NOT NULL,
    customer_phone VARCHAR(20) NOT NULL,
    ticket_type_summary NVARCHAR(100), -- 'VIP', 'Thường', 'Sinh viên'
    total_quantity INT NOT NULL DEFAULT 1,
    subtotal DECIMAL(18,2) NOT NULL,
    service_fee DECIMAL(18,2) NOT NULL DEFAULT 0,
    discount_amount DECIMAL(18,2) NOT NULL DEFAULT 0,
    total_amount DECIMAL(18,2) NOT NULL,
    payment_method VARCHAR(30) NOT NULL DEFAULT 'bank', -- 'bank', 'qr', 'wallet', 'intl'
    payment_status NVARCHAR(50) NOT NULL DEFAULT N'Chờ thanh toán', -- N'Đã thanh toán', N'Chờ thanh toán', N'Đã hủy'
    order_time_desc NVARCHAR(50), -- '10:42 hôm nay'
    checked_in_qty INT NOT NULL DEFAULT 0, -- số vé đã soát vào cổng
    last_checkin_at DATETIME NULL,
    payment_ref VARCHAR(100) NULL, -- mã giao dịch VNPay (hoặc WAITING-VNPAY khi đang chờ thanh toán)
    created_at DATETIME DEFAULT GETDATE(),
    FOREIGN KEY (user_id) REFERENCES Users(user_id),
    FOREIGN KEY (event_id) REFERENCES Events(event_id)
);
GO

-- 6. BẢNG CHI TIẾT ĐƠN HÀNG (OrderDetails)
CREATE TABLE OrderDetails (
    order_detail_id INT IDENTITY(1,1) PRIMARY KEY,
    order_id INT NOT NULL,
    ticket_type_id INT NOT NULL,
    quantity INT NOT NULL,
    unit_price DECIMAL(18,2) NOT NULL,
    amount DECIMAL(18,2) NOT NULL,
    FOREIGN KEY (order_id) REFERENCES Orders(order_id) ON DELETE CASCADE,
    FOREIGN KEY (ticket_type_id) REFERENCES TicketTypes(ticket_type_id)
);
GO

-- 7. BẢNG CÀI ĐẶT HỆ THỐNG (Settings) - phí dịch vụ, mã giảm giá, thông tin liên hệ...
CREATE TABLE Settings (
    setting_key VARCHAR(60) PRIMARY KEY,
    setting_value NVARCHAR(500) NOT NULL
);
GO

